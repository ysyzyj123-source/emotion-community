    rows = []
    for topic, texts in TOPIC_CORPUS.items():
        for t in texts:
            rows.append({"text": t, "topic": topic})
    random.shuffle(rows)
    with open(OUT, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"语料生成: {len(rows)} 条, 主题: {list(TOPIC_CORPUS.keys())}")


