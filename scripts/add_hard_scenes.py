def add(rows, pool, sentiment, emergency, vmin, vmax, scale=1):
    n = 0
    for text in pool:
        for _ in range(max(1, scale)):
            rows.append({'text': text, 'sentiment': sentiment, 'emergency': emergency,
                         'valence': round(random.uniform(vmin, vmax), 1)})
            n += 1
    return n

added = 0
# 每类 scale 大幅提高（几十条基础句 × 几十倍 = 每类几百条，总计几千条难样本）
scale = 30
added += add(rows, IRONY, 0, 1, -8.0, -5.0, scale=scale)
added += add(rows, RHETORIC, 0, 1, -7.5, -4.5, scale=scale)
added += add(rows, UNFAIR, 0, 1, -7.0, -4.0, scale=scale)
added += add(rows, HELP, 0, 1, -8.0, -5.0, scale=scale)
added += add(rows, BRAVE, 0, 1, -6.0, -3.5, scale=scale)
added += add(rows, DOWNTONE, 0, 1, -6.0, -3.0, scale=scale)
added += add(rows, CONFUSE, 0, 1, -6.5, -3.5, scale=scale)

